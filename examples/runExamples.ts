import { pollinationsClient } from '../src/pollinations/client.js';
import { ReActEngine } from '../src/react/engine.js';
import { CrewCoordinator, AgentRole } from '../src/agents/crew.js';
import { getAllToolDefinitions } from '../src/tools/devTools.js';

// ============================================================================
// EXAMPLE 1: Simple ReAct Task
// ============================================================================
async function example1_simpleReact() {
  console.log('═══ Example 1: Simple ReAct Loop ═══\n');

  const engine = new ReActEngine({
    model: 'claude',
    maxSteps: 5,
    verbose: true,
  });

  console.log('Task: "Create a simple hello world Python script"\n');

  const result = await engine.run('Create a Python script that prints "Hello, World!" with a timestamp');

  console.log('\n──────── Result ────────');
  if (result.success) {
    console.log('✅ Completed in', result.stepCount, 'steps');
    console.log('Answer:', result.finalAnswer);
  } else {
    console.log('❌ Failed:', result.error);
  }
}

