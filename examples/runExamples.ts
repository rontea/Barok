// ============================================================================
// EXAMPLE 4: Direct Tool Use
// ============================================================================
async function example4_directTools() {
  console.log('\n═══ Example 4: Direct Tool Invocation ═══\n');

  const tools = getAllToolDefinitions();
  console.log(`Available dev tools: ${tools.map(t => t.name).join(', ')}\n`);

  // Bash example
  console.log('Running: Bash({ command: "node --version" })');
  const bashTool = tools.find(t => t.name === 'Bash');
  if (bashTool) {
    const result = await bashTool.handler({ command: 'node --version' });
    console.log('Output:', result.output);
  }

  // File write example
  const writeTool = tools.find(t => t.name === 'Write');
  if (writeTool) {
    console.log('\nWriting test file...');
    await writeTool.handler({
      file_path: './test-output.txt',
      content: 'Generated by Raw ReAct MCP\nTimestamp: ' + new Date().toISOString(),
    });
    console.log('✅ File written');
  }

  // Read it back
  const readTool = tools.find(t => t.name === 'Read');
  if (readTool) {
    const readResult = await readTool.handler({ file_path: './test-output.txt' });
    console.log('Read back:', readResult.output);
  }
}

